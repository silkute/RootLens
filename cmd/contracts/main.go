// contracts generates OpenAPI and TypeScript from Go transport types.
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"reflect"
	"rootlens/internal/protocol"
	"rootlens/internal/storage"
	"sort"
	"strings"
	"time"
)

var types = []reflect.Type{reflect.TypeOf(protocol.Capability{}), reflect.TypeOf(protocol.Entity{}), reflect.TypeOf(protocol.Sample{}), reflect.TypeOf(protocol.Frame{}), reflect.TypeOf(protocol.Event{}), reflect.TypeOf(protocol.Batch{}), reflect.TypeOf(protocol.Ack{}), reflect.TypeOf(protocol.Evidence{}), reflect.TypeOf(protocol.Contributor{}), reflect.TypeOf(protocol.Incident{}), reflect.TypeOf(protocol.Host{}), reflect.TypeOf(protocol.MetricPoint{}), reflect.TypeOf(protocol.MetricSeries{}), reflect.TypeOf(protocol.Metric{}), reflect.TypeOf(protocol.MetricsResponse{}), reflect.TypeOf(storage.Retention{})}

func ts(t reflect.Type) string {
	if t == reflect.TypeOf(time.Time{}) {
		return "string"
	}
	switch t.Kind() {
	case reflect.Pointer:
		return ts(t.Elem()) + " | null"
	case reflect.String:
		return "string"
	case reflect.Bool:
		return "boolean"
	case reflect.Int, reflect.Int64, reflect.Float64:
		return "number"
	case reflect.Slice:
		return "Array<" + ts(t.Elem()) + ">"
	case reflect.Map:
		return "Record<string, " + ts(t.Elem()) + ">"
	case reflect.Struct:
		return t.Name()
	}
	panic(t.String())
}
func schema(t reflect.Type) map[string]any {
	if t == reflect.TypeOf(time.Time{}) {
		return map[string]any{"type": "string", "format": "date-time"}
	}
	switch t.Kind() {
	case reflect.Pointer:
		return map[string]any{"anyOf": []any{schema(t.Elem()), map[string]any{"type": "null"}}}
	case reflect.String:
		return map[string]any{"type": "string"}
	case reflect.Bool:
		return map[string]any{"type": "boolean"}
	case reflect.Int, reflect.Int64:
		return map[string]any{"type": "integer"}
	case reflect.Float64:
		return map[string]any{"type": "number"}
	case reflect.Slice:
		return map[string]any{"type": "array", "items": schema(t.Elem())}
	case reflect.Map:
		return map[string]any{"type": "object", "additionalProperties": schema(t.Elem())}
	case reflect.Struct:
		return map[string]any{"$ref": "#/components/schemas/" + t.Name()}
	}
	panic(t.String())
}
func main() {
	types = append(types, reflect.TypeOf(protocol.Process{}), reflect.TypeOf(protocol.ProcessSnapshot{}))
	types = append(types, reflect.TypeOf(protocol.SetupRequest{}), reflect.TypeOf(protocol.LoginRequest{}), reflect.TypeOf(protocol.CreateHostRequest{}), reflect.TypeOf(protocol.EnrollmentRequest{}), reflect.TypeOf(protocol.InvestigationRequest{}))
	schemas := map[string]any{}
	var output strings.Builder
	output.WriteString("// Code generated by go run ./cmd/contracts. DO NOT EDIT.\n")
	for _, t := range types {
		properties := map[string]any{}
		required := []string{}
		fmt.Fprintf(&output, "export interface %s {\n", t.Name())
		for i := 0; i < t.NumField(); i++ {
			f := t.Field(i)
			tag := strings.Split(f.Tag.Get("json"), ",")
			name := tag[0]
			if name == "" {
				name = f.Name
			}
			optional := ""
			if len(tag) > 1 && tag[1] == "omitempty" {
				optional = "?"
			} else {
				required = append(required, name)
			}
			fmt.Fprintf(&output, "  %s%s: %s\n", name, optional, ts(f.Type))
			properties[name] = schema(f.Type)
		}
		output.WriteString("}\n")
		schemas[t.Name()] = map[string]any{"type": "object", "properties": properties, "required": required, "additionalProperties": false}
	}
	paths := map[string]any{}
	routes := map[string][]string{"/me": {"get"}, "/setup": {"post"}, "/session": {"post", "delete"}, "/hosts": {"get", "post"}, "/hosts/{id}": {"get"}, "/hosts/{id}/enrollment-tokens": {"post"}, "/agent/enroll": {"post"}, "/agent/batches": {"post"}, "/hosts/{id}/credentials": {"get"}, "/hosts/{id}/credentials/{credential}": {"delete"}, "/hosts/{id}/credentials/rotate": {"post"}, "/hosts/{id}/metrics": {"get"}, "/hosts/{id}/containers": {"get"}, "/containers/{id}": {"get"}, "/hosts/{id}/processes": {"get"}, "/incidents": {"get"}, "/incidents/{id}": {"get"}, "/incidents/{id}/report": {"get"}, "/incidents/{id}/evidence": {"get"}, "/events": {"get"}, "/hosts/{id}/diagnostics": {"get"}, "/hosts/{id}/investigations": {"post"}, "/settings": {"get", "patch"}, "/health/storage": {"get"}}
	for route, methods := range routes {
		item := map[string]any{}
		for _, method := range methods {
			op := map[string]any{"summary": method + " " + route, "responses": map[string]any{"200": map[string]any{"description": "Successful response; see docs/api.md."}, "400": map[string]any{"description": "Invalid or oversized input"}, "401": map[string]any{"description": "Authentication required"}, "403": map[string]any{"description": "Permission or CSRF failure"}, "503": map[string]any{"description": "Storage unavailable; retry without discarding data"}}}
			security := []any{map[string]any{"sessionCookie": []string{}}}
			if strings.HasPrefix(route, "/agent/") {
				security = []any{map[string]any{"agentBearer": []string{}}}
			}
			if route == "/agent/enroll" || route == "/setup" || route == "/session" && method == "post" || route == "/me" {
				security = []any{}
			}
			op["security"] = security
			parameters := []any{}
			for _, name := range []string{"id", "credential"} {
				if strings.Contains(route, "{"+name+"}") {
					parameters = append(parameters, map[string]any{"name": name, "in": "path", "required": true, "schema": map[string]any{"type": "string"}})
				}
			}
			if method != "get" && !strings.HasPrefix(route, "/agent/") && route != "/setup" && route != "/session" {
				parameters = append(parameters, map[string]any{"name": "X-CSRF-Token", "in": "header", "required": true, "schema": map[string]any{"type": "string"}})
			}
			if len(parameters) > 0 {
				op["parameters"] = parameters
			}
			if route == "/agent/batches" {
				op["requestBody"] = map[string]any{"required": true, "content": map[string]any{"application/json": map[string]any{"schema": map[string]any{"$ref": "#/components/schemas/Batch"}}}}
			}
			item[method] = op
		}
		paths["/api/v1"+route] = item
	}
	requestTypes := map[string]string{"post /setup": "SetupRequest", "post /session": "LoginRequest", "post /hosts": "CreateHostRequest", "post /agent/enroll": "EnrollmentRequest", "post /agent/batches": "Batch", "post /hosts/{id}/investigations": "InvestigationRequest", "patch /settings": "Retention"}
	responseTypes := map[string]string{"get /hosts": "Host[]", "get /hosts/{id}": "Host", "post /agent/batches": "Ack", "get /hosts/{id}/metrics": "MetricsResponse", "get /incidents": "Incident[]", "get /incidents/{id}": "Incident", "get /events": "Event[]", "get /settings": "Retention", "patch /settings": "Retention"}
	for key, name := range requestTypes {
		parts := strings.SplitN(key, " ", 2)
		op := paths["/api/v1"+parts[1]].(map[string]any)[parts[0]].(map[string]any)
		op["requestBody"] = map[string]any{"required": true, "content": map[string]any{"application/json": map[string]any{"schema": map[string]any{"$ref": "#/components/schemas/" + name}}}}
	}
	for key, name := range responseTypes {
		parts := strings.SplitN(key, " ", 2)
		op := paths["/api/v1"+parts[1]].(map[string]any)[parts[0]].(map[string]any)
		ref := map[string]any{"$ref": "#/components/schemas/" + strings.TrimSuffix(name, "[]")}
		var responseSchema any = ref
		if strings.HasSuffix(name, "[]") {
			responseSchema = map[string]any{"type": "array", "items": ref}
		}
		op["responses"].(map[string]any)["200"] = map[string]any{"description": "Success", "content": map[string]any{"application/json": map[string]any{"schema": responseSchema}}}
	}
	for _, route := range []string{"/setup", "/hosts", "/agent/enroll", "/hosts/{id}/enrollment-tokens", "/hosts/{id}/credentials/rotate"} {
		op := paths["/api/v1"+route].(map[string]any)["post"].(map[string]any)
		responses := op["responses"].(map[string]any)
		delete(responses, "200")
		responses["201"] = map[string]any{"description": "Created"}
	}
	for _, route := range []string{"/session", "/hosts/{id}/credentials/{credential}"} {
		op := paths["/api/v1"+route].(map[string]any)["delete"].(map[string]any)
		responses := op["responses"].(map[string]any)
		delete(responses, "200")
		responses["204"] = map[string]any{"description": "Completed"}
	}
	for _, route := range []string{"/hosts/{id}/metrics"} {
		op := paths["/api/v1"+route].(map[string]any)["get"].(map[string]any)
		parameters := op["parameters"].([]any)
		for _, name := range []string{"from", "to", "entity"} {
			parameters = append(parameters, map[string]any{"name": name, "in": "query", "schema": map[string]any{"type": "string"}, "description": "RFC3339 time, or an entity identifier"})
		}
		op["parameters"] = parameters
	}
	batchProperties := schemas["Batch"].(map[string]any)["properties"].(map[string]any)
	for field, limit := range map[string]int{"frames": 120, "entities": 512, "events": 256} {
		batchProperties[field].(map[string]any)["maxItems"] = limit
	}
	batchProperties["protocol"].(map[string]any)["enum"] = []int{1}
	batchProperties["sampling_seconds"].(map[string]any)["enum"] = []int{5, 10, 15}
	doc := map[string]any{"openapi": "3.1.0", "info": map[string]any{"title": "RootLens API", "version": protocol.Version}, "paths": paths, "components": map[string]any{"schemas": schemas, "securitySchemes": map[string]any{"sessionCookie": map[string]any{"type": "apiKey", "in": "cookie", "name": "rootlens_session"}, "agentBearer": map[string]any{"type": "http", "scheme": "bearer"}}}}
	data, e := json.MarshalIndent(doc, "", "  ")
	if e != nil {
		panic(e)
	}
	os.MkdirAll("api", 0755)
	if e = os.WriteFile("api/openapi.json", append(data, '\n'), 0644); e != nil {
		panic(e)
	}
	if e = os.WriteFile("web/src/contracts.generated.ts", []byte(output.String()), 0644); e != nil {
		panic(e)
	}
	keys := []string{}
	for key := range protocol.Registry {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	var md strings.Builder
	md.WriteString("# Metric registry\n\nGenerated from the Go transport registry. Chart API delta metrics are rates per second.\n\n| Key | Source unit | Kind | Interpretation |\n|---|---|---|---|\n")
	for _, key := range keys {
		m := protocol.Registry[key]
		fmt.Fprintf(&md, "| `%s` | %s | %s | %s |\n", key, m.Unit, m.Kind, m.Description)
	}
	if e = os.WriteFile("api/metrics.md", []byte(md.String()), 0644); e != nil {
		panic(e)
	}
}
